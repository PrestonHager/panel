#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const tokensPath = path.join(root, 'resources/design/tokens.json');
const outputPath = path.join(root, 'public/plugins/panel-tokens.css');

function tokenToVar(key) {
    return '--pt-' + key.replace(/\./g, '-');
}

function emitBlock(selector, values) {
    const lines = Object.entries(values).map(
        ([key, value]) => `    ${tokenToVar(key)}: ${value};`
    );

    return `${selector} {\n${lines.join('\n')}\n}\n`;
}

function main() {
    const raw = fs.readFileSync(tokensPath, 'utf8');
    const data = JSON.parse(raw);
    const surfaces = data.surfaces || {};

    let css = '/* Generated by scripts/build-design-tokens.js — do not edit manually */\n\n';

    if (surfaces.client) {
        css += emitBlock(':root, [data-pt-surface="client"]', surfaces.client);
        css += '\n';
    }

    if (surfaces.admin) {
        css += emitBlock('[data-pt-surface="admin"], .ptero-plugin--admin', surfaces.admin);
        css += '\n';
    }

    css += '/* Legacy alias: admin plugin tabs inside AdminLTE boxes */\n';
    css += '.ptero-plugin--on-light {\n    color: var(--pt-color-text);\n}\n';

    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, css);
    console.log('Wrote', outputPath);
}

main();
